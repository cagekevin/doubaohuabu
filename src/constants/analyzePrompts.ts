/**
 * 提示词分析 —— **模型指令**（发给 AI 的 prompt，原 `ND` / `ED`）
 *
 * ⚠️ **为什么单独成文件而不是塞进 `text.ts`**：
 *   `text.ts` 的自我定位是「**UI 文案**的 SSOT」（面向**用户**的字符串）。
 *   这里是**发给模型的指令**——用户看不到、也不需要本地化 ⇒ 两类东西混在一起会
 *   让 `text.ts` 的"唯一真源"含义变糊。故按**类别**分文件（`constants/` 下已有
 *   `failure` / `models` / `inputLock` / `stylePresets` 等多个文件，是既有惯例）。
 *
 * ⚠️ **逐字回源抄录**（`shared.js:38664-38700` 与 `38720-38735`），含：
 *   · 换行符是 **`\r\n`**（源版 `.join(\`\\r\\n\`)`）—— 不是 `\n`，改动会变更模型输入
 *   · 全角标点、方括号、【】、引号一律原样
 */

