/**
 * 按用户意见**调整**提示词的指令（原 `ED` shared.js:38720）
 *
 * @param currentJson 当前提示词（原版传 `o.raw`（字符串）或 `JSON.stringify(json_prompt)`）
 * @param instruction 用户修改意见（**调用方负责 trim** —— 源版 `yS` 先 trim 再传进来）
 */
export function buildReviseInstruction(currentJson: unknown, instruction: string): string {
  return [
    '请基于下面提供的「当前图像提示词 JSON」，严格按照用户的修改意见进行调整，并输出修改后的完整 JSON。',
    '要求：',
    '1. 保持与当前 JSON 完全相同的结构：zh_prompt（中文，不少于 200 字）、en_prompt（英文，不少于 200 个字符）、json_prompt（subject, style, composition, lighting, color, texture, effects, camera, quality 这 9 个字段，值为字符串数组）。',
    '2. 修改要通篇合理同步：改动某处后，与之相关的风格、光影、色彩、构图、材质等描述都要联动调整，不要只替换局部词语。',
    '3. 未被修改意见涉及的内容尽量保留原样，保持还原度。',
    '4. 只输出一个合法 JSON 对象，不要输出 markdown，不要输出解释文字。',
    `用户修改意见：${String(instruction || '').trim()}`,
    '当前图像提示词 JSON：',
    String(currentJson ?? ''),
  ].join('\r\n');
}
